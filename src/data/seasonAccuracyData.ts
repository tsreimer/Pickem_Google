export interface WeeklyAccuracyRecord {
  week: number;
  weekLabel: string;
  gamesCount: number;
  correctCount: number;
  accuracy: number; // Straight-up win % (e.g. 68.8)
  pointsEarned: number;
  pointsPossible: number;
  confidenceEfficiency: number; // % of confidence points earned (e.g. 74.2)
  leagueAvgAccuracy: number; // League average straight-up %
  leagueAvgEfficiency: number; // League average points efficiency %
  vegasFavoriteAccuracy: number; // Vegas chalk accuracy %
  topPerformerAccuracy: number; // Best team accuracy that week
  cumulativeAccuracy: number; // Cumulative season accuracy % up to this week
  cumulativeEfficiency: number; // Cumulative points efficiency % up to this week
  cumulativeLeagueAvg: number;
  anchorRecord: string; // e.g. "3/4 (75%)" on 13-16 pt picks
  anchorAccuracy: number; // % on top anchors
  weeklyRank: number;
  highlight: string;
  notes: string;
}

export interface TeamSeasonAccuracy {
  teamId: string;
  teamName: string;
  ownerName: string;
  avatar: string;
  color: string;
  currentSeasonAccuracy: number;
  currentSeasonEfficiency: number;
  seasonRecord: string; // e.g. "17-15"
  totalPointsScored: number;
  totalPointsPossible: number;
  anchorHitRate: number; // Top anchors (13-16) %
  upsetCorrectCount: number;
  leagueAccuracyRank: number;
  momentum: 'surging' | 'steady' | 'rebounding' | 'volatile';
  momentumText: string;
  bestWeek: { week: number; accuracy: number; points: number };
  toughestWeek: { week: number; accuracy: number; points: number };
  weeklyTrends: WeeklyAccuracyRecord[];
}

